import os
import json
import re
from datetime import datetime
import chromadb
from chromadb.utils import embedding_functions

def generate_unified_theory(collection, pipe, tokenizer, focus_areas=None, output_dir=None):
    if output_dir is None:
        output_dir = "/content/drive/MyDrive/Discovery_AI_Workspace/vault/theories"
    os.makedirs(output_dir, exist_ok=True)

    # 1. Retrieve all or cluster-focused nodes from ChromaDB
    all_data = collection.get()
    docs = all_data.get("documents", [])
    metas = all_data.get("metadatas", [])
    
    if not docs:
        print("[Autonomous Runner] No nodes found in ChromaDB collection.")
        return None

    # Construct complete entity relation summary
    knowledge_summary = []
    for i in range(len(docs)):
        title = metas[i].get("title", "Unknown")
        cluster = metas[i].get("cluster", "General")
        connections = metas[i].get("connected_to", "")
        doc = docs[i]
        knowledge_summary.append(f"• [{cluster}] {title}: {doc} (Links: {connections})")

    context_str = "\n".join(knowledge_summary)

    # 2. Hermes Synthesis Prompt for Autonomous Theory Formulation
    system_prompt = (
        "You are the autonomous theoretical reasoning brain of Discovery AI. "
        "Your task is to analyze the entire interconnected knowledge base and synthesize an original, "
        "rigorous, and cohesive grand unified hypothesis or theory. "
        "Connect secret space operations, ancient builder artifacts, subterranean logistics, and metaphysical ascension."
    )

    user_prompt = f"""KNOWLEDGE GRAPH DATA:
{context_str}

TASK:
Synthesize an autonomous theoretical paper analyzing the underlying systemic narrative.
Structure your theoretical output as follows:
# TITLE: [Comprehensive Title]
## 1. ABSTRACT & CORE THESIS
## 2. CROSS-DOMAIN MECHANISMS (Space Programs, Ancient Builder Artifacts & Subterranean Logistics)
## 3. METAPHYSICAL & CONSCIOUSNESS DYNAMICS
## 4. SYSTEMIC ANOMALIES & THEORETICAL IMPLICATIONS
## 5. HYPOTHESES FOR FURTHER VERIFICATION
"""

    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_prompt}
    ]

    prompt = tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)

    print("[Autonomous Runner] Hermes 7B is synthesizing unified theoretical framework...")
    outputs = pipe(
        prompt,
        max_new_tokens=1024,
        temperature=0.3,
        pad_token_id=tokenizer.eos_token_id,
        return_full_text=False
    )

    theory_text = outputs[0]["generated_text"].strip()

    # 3. Save to vault/theories
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    theory_filename = f"theory_synthesis_{timestamp}.md"
    theory_path = os.path.join(output_dir, theory_filename)

    with open(theory_path, "w", encoding="utf-8") as f:
        f.write(f"<!-- Generated by Discovery AI Autonomous Runner on {datetime.now().isoformat()} -->\n\n")
        f.write(theory_text)

    print(f"[Autonomous Runner] Theory successfully synthesized and saved to:\n-> {theory_path}")
    return theory_text, theory_path
